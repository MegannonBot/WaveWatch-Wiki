#!/usr/bin/env python3
"""Generate wiki/index.md from page frontmatter. Never hand-edit the index.

Usage:  python3 tools/wiki_build.py          write wiki/index.md
        python3 tools/wiki_build.py --check  exit 1 if the index is out of date
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WIKI = os.path.join(ROOT, "wiki")

SECTIONS = [
    ("decision", "Decisions and proposals"),
    ("spec", "Specs"),
    ("entity", "Entities"),
    ("concept", "Concepts"),
    ("research", "Research"),
    ("runbook", "Runbooks"),
    ("report", "Session reports"),
]
ENTRY_POINTS = [
    ("STATE", "Current state. Read first, every session."),
    ("log", "What happened, newest first. Read on demand."),
    ("mistakes", "Failure patterns and the check that catches each."),
]


def frontmatter(path):
    meta = {}
    with open(path, encoding="utf-8") as fh:
        lines = fh.read().split("\n")
    if not lines or lines[0].strip() != "---":
        return meta
    for line in lines[1:]:
        if line.strip() == "---":
            break
        if ":" in line:
            key, _, value = line.partition(":")
            meta[key.strip()] = value.strip().strip('"')
    return meta


def pages():
    out = []
    for dirpath, dirnames, filenames in os.walk(WIKI):
        dirnames[:] = sorted(d for d in dirnames if not d.startswith("."))
        for name in sorted(filenames):
            if not name.endswith(".md"):
                continue
            full = os.path.join(dirpath, name)
            rel = os.path.relpath(full, WIKI).replace(os.sep, "/")[:-3]
            out.append((rel, frontmatter(full)))
    return out


def latest_date(all_pages):
    dates = [m.get("last_updated", "") for rel, m in all_pages if rel != "index"]
    dates = [d for d in dates if d]
    return max(dates) if dates else ""


def build():
    all_pages = pages()
    lines = [
        "---",
        "type: index",
        "title: WaveWatch index",
        "summary: Generated catalogue of every page in the vault.",
        "status: active",
        "last_updated: " + latest_date(all_pages),
        "---",
        "",
        "# WaveWatch index",
        "",
        "> Generated by `tools/wiki_build.py` from page frontmatter. Do not edit by hand.",
        "",
        "## Start here",
        "",
    ]
    for rel, text in ENTRY_POINTS:
        lines.append("- [[" + rel + "]]: " + text)
    lines.append("")

    for ptype, heading in SECTIONS:
        rows = [(rel, m) for rel, m in all_pages if m.get("type") == ptype]
        if not rows:
            continue
        lines += ["## " + heading, "", "| Page | Summary | Status |", "|---|---|---|"]
        for rel, m in sorted(rows, key=lambda r: r[0]):
            summary = m.get("summary", "").replace("|", "/")
            lines.append("| [[" + rel + "]] | " + summary + " | " + m.get("status", "") + " |")
        lines.append("")

    known = {t for t, _ in SECTIONS} | {"state", "log", "mistakes", "index"}
    other = [(rel, m) for rel, m in all_pages if m.get("type") not in known]
    if other:
        lines += ["## Unclassified (fix the frontmatter)", ""]
        for rel, m in other:
            lines.append("- [[" + rel + "]]")
        lines.append("")

    count = len([1 for rel, _ in all_pages if rel != "index"])
    lines.append("*" + str(count) + " pages.*")
    return "\n".join(lines) + "\n"


def main():
    text = build()
    target = os.path.join(WIKI, "index.md")
    if "--check" in sys.argv:
        current = open(target, encoding="utf-8").read() if os.path.exists(target) else ""
        if current != text:
            print("index.md is out of date. Run: python3 tools/wiki_build.py")
            sys.exit(1)
        print("index.md is up to date.")
        return
    with open(target, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote wiki/index.md")


if __name__ == "__main__":
    main()
