#!/usr/bin/env python3
"""PreToolUse guard for the WaveWatch vault (Claude Code sessions).

Reads the hook payload as JSON on stdin. Exit code 2 refuses the tool call and
shows the message on stderr to the session. Exit code 0 allows it.

Refuses:
  1. Editing or overwriting an existing file under raw/ (sources are immutable).
  2. Hand-editing wiki/index.md (it is generated by tools/wiki_build.py).
  3. A git force-push.
  4. Writing an em dash into any file.
"""
import json
import os
import re
import sys

EM_DASH = chr(0x2014)


def refuse(msg):
    sys.stderr.write("WaveWatch guard: " + msg + "\n")
    sys.exit(2)


def main():
    try:
        payload = json.load(sys.stdin)
    except Exception:
        sys.exit(0)

    tool = payload.get("tool_name", "")
    data = payload.get("tool_input", {}) or {}
    root = os.environ.get("CLAUDE_PROJECT_DIR") or payload.get("cwd") or os.getcwd()

    if tool in ("Edit", "Write", "MultiEdit"):
        path = data.get("file_path", "")
        rel = os.path.relpath(os.path.abspath(path), os.path.abspath(root)) if path else ""
        rel = rel.replace(os.sep, "/")

        if rel.startswith("raw/"):
            if tool != "Write" or os.path.exists(path):
                refuse("raw/ is immutable. Add a new file; never edit or overwrite a source.")

        if rel == "wiki/index.md":
            refuse("wiki/index.md is generated. Run: python3 tools/wiki_build.py")

        new_text = " ".join(
            str(v)
            for v in (
                data.get("content"),
                data.get("new_string"),
                json.dumps(data.get("edits"), ensure_ascii=False) if data.get("edits") else None,
            )
            if v
        )
        if EM_DASH in new_text:
            refuse("no em dashes in this vault (CLAUDE.md, Language rule 3). Rewrite the sentence.")

    if tool == "Bash":
        cmd = data.get("command", "")
        if re.search(r"\bgit\b[^|;&]*\bpush\b[^|;&]*(--force\b|--force-with-lease\b|\s-f\b|\s\+\S+)", cmd):
            refuse("force-push is forbidden (CLAUDE.md, Git and transport rule 3).")

    sys.exit(0)


if __name__ == "__main__":
    main()
